def _referenced_asset_ids(project: dict[str, Any]) -> set[str]:
    assets = project.get("assets", [])
    by_name: dict[str, str] = {}
    by_id: set[str] = set()
    for asset in assets:
        asset_id = str(asset.get("id", ""))
        by_id.add(asset_id)
        by_name[str(asset.get("name", ""))] = asset_id
        by_name[Path(str(asset.get("path", ""))).name] = asset_id
    referenced = {str(asset.get("id")) for asset in assets if asset.get("forceBundle")}
    title = project.get("ui", {}).get("title", {})
    referenced.update(str(asset_id) for asset_id in (title.get("backgroundAssetId"), title.get("logoAssetId")) if asset_id)
    runtime_theme = project.get("ui", {}).get("runtimeTheme", {})
    if runtime_theme.get("fontAssetId"):
        referenced.add(str(runtime_theme["fontAssetId"]))
    for character in project.get("characters", []):
        referenced.update(str(asset_id) for asset_id in character.get("portraits", {}).values() if asset_id)
        referenced.update(str(overlay["assetId"]) for overlay in character.get("overlays", []) if overlay.get("assetId"))
    for blocks in project.get("scripts", {}).values():
        for block in blocks:
            if block.get("assetId"):
                referenced.add(str(block["assetId"]))
            for layer in block.get("layers", []):
                if layer.get("assetId"):
                    referenced.add(str(layer["assetId"]))
            voice = str(block.get("voice", ""))
            if voice in by_id:
                referenced.add(voice)
            elif voice and voice in by_name:
                referenced.add(by_name[voice])
    return referenced


def build_web_game(
    project: dict[str, Any],
    output_dir: Path,
    project_path: Path,
    builtin_assets: Path,
    custom_assets: Path | None = None,
    runtime_dist: Path | None = None,
) -> Path:
    if runtime_dist is None:
        raise ValueError("Web runtime directory is required")
    runtime_js = runtime_dist / "player.js"
    runtime_css = runtime_dist / "player.css"
    if not runtime_js.is_file() or not runtime_css.is_file():
        raise FileNotFoundError("Shared engine-core runtime is missing. Run the frontend production build first.")
    if output_dir.exists():
        shutil.rmtree(output_dir)
    assets_dir = output_dir / "assets"
    assets_dir.mkdir(parents=True, exist_ok=True)
    exported = json.loads(json.dumps(project, ensure_ascii=False))
    enabled_fragment_ids = {
        fragment["id"]
        for chapter in exported.get("chapters", []) if not chapter.get("disabled")
        for fragment in chapter.get("fragments", [])
    }
    exported["chapters"] = [chapter for chapter in exported.get("chapters", []) if not chapter.get("disabled")]
    exported["scripts"] = {
        fragment_id: blocks for fragment_id, blocks in exported.get("scripts", {}).items()
        if fragment_id in enabled_fragment_ids
    }
    if exported.get("activeFragmentId") not in enabled_fragment_ids and enabled_fragment_ids:
        exported["activeFragmentId"] = next(iter(enabled_fragment_ids))
    referenced_ids = _referenced_asset_ids(exported)
    exported["assets"] = [asset for asset in exported.get("assets", []) if str(asset.get("id")) in referenced_ids]
    custom_asset_dir = custom_assets or project_path.parent / f"{project_path.stem}.assets"
    for asset in exported.get("assets", []):
        source: Path | None = None
        path_value = str(asset.get("path", ""))
        if path_value.startswith("builtin/") or (path_value.startswith("assets/") and (builtin_assets / Path(path_value).name).is_file()):
            source = builtin_assets / Path(path_value).name
        elif path_value:
            source = custom_asset_dir / Path(path_value).name
        if source and source.is_file():
            destination = assets_dir / source.name
            shutil.copy2(source, destination)
            asset["exportPath"] = f"assets/{destination.name}"
            asset["uri"] = asset["exportPath"]
        else:
            asset.pop("uri", None)
    (output_dir / "index.html").write_text(PLAYER_HTML, encoding="utf-8")
    shutil.copy2(runtime_css, output_dir / "player.css")
    shutil.copy2(runtime_js, output_dir / "player.js")
    (output_dir / "project.js").write_text("window.HIKARI_PROJECT=" + json.dumps(exported, ensure_ascii=False) + ";", encoding="utf-8")
    return output_dir / "index.html"
