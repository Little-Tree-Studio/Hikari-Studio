def safe_slug(value: str) -> str:
    slug = re.sub(r"[^\w\-\u4e00-\u9fff]+", "-", value.strip()).strip("-")
    return slug or "hikari-game"


def renpy_identifier(value: str) -> str:
    normalized = re.sub(r"\W+", "_", value, flags=re.UNICODE).strip("_")
    if not normalized or not normalized[0].isalpha():
        normalized = f"label_{normalized}"
    return normalized.lower()


def quote(value: Any) -> str:
    return json.dumps(str(value or ""), ensure_ascii=False)


def python_literal(value: Any) -> str:
    return repr(value)


def export_renpy(project: dict[str, Any], output_dir: Path) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    enabled_chapters = [chapter for chapter in project["chapters"] if not chapter.get("disabled")]
    fragment_names = {
        fragment["id"]: renpy_identifier(fragment["id"])
        for chapter in enabled_chapters for fragment in chapter.get("fragments", [])
    }
    character_names = sorted({
        block.get("speaker") for blocks in project["scripts"].values()
        for block in blocks if block.get("type") == "dialogue" and block.get("speaker")
    })
    character_ids = {name: f"char_{index}" for index, name in enumerate(character_names, 1)}
    lines = ["# Generated by Hikari Studio", "", "default _hikari_vars = {}", ""]
    for name, identifier in character_ids.items():
        lines.append(f"define {identifier} = Character({quote(name)})")
    lines.extend(["", "label start:"])
    entry_fragment = enabled_chapters[0]["fragments"][0]["id"]
    lines.extend([f"    call {fragment_names[entry_fragment]}", "    return", ""])
    for chapter in enabled_chapters:
        lines.append(f"# {chapter['name']}")
        for fragment in chapter.get("fragments", []):
            lines.append(f"label {fragment_names[fragment['id']]}:")
            blocks = project["scripts"].get(fragment["id"], [])
            if not blocks:
                lines.append("    pass")
            for block in blocks:
                block_type = block.get("type")
                if block_type == "narration":
                    lines.append(f"    {quote(block.get('text'))}")
                elif block_type == "dialogue":
                    speaker = character_ids.get(block.get("speaker"), "narrator")
                    lines.append(f"    {speaker} {quote(block.get('text'))}")
                elif block_type == "scene":
                    lines.append(f"    # scene {block.get('title', '')} with {block.get('transition', 'dissolve')}")
                elif block_type == "sound":
                    lines.append(f"    play music {quote(block.get('title'))} {'loop' if block.get('loop') else ''}".rstrip())
                elif block_type == "branch":
                    lines.append(f"    menu {quote(block.get('title', '请选择'))}:")
                    for option in block.get("options", []):
                        target = fragment_names.get(option.get("target"))
                        lines.append(f"        {quote(option.get('text'))}:")
                        lines.append(f"            {'call ' + target if target else 'pass'}")
                elif block_type == "setVariable":
                    lines.append(f"    $ _hikari_vars[{quote(block.get('variable'))}] = {python_literal(block.get('value'))}")
                elif block_type == "condition":
                    operators = {"eq": "==", "neq": "!=", "gt": ">", "gte": ">=", "lt": "<", "lte": "<="}
                    operator = operators.get(block.get("operator"), "==")
                    lines.append(f"    if _hikari_vars.get({quote(block.get('variable'))}) {operator} {python_literal(block.get('compareValue'))}:")
                    true_target = fragment_names.get(block.get("trueTarget"))
                    lines.append(f"        {'jump ' + true_target if true_target else 'pass'}")
                    false_target = fragment_names.get(block.get("falseTarget"))
                    if false_target:
                        lines.extend(["    else:", f"        jump {false_target}"])
                elif block_type in {"jump", "call"}:
                    target = fragment_names.get(block.get("target"))
                    lines.append(f"    {block_type + ' ' + target if target else 'pass'}")
                elif block_type == "return":
                    lines.append("    return")
            lines.extend(["    return", ""])
    output = output_dir / "script.rpy"
    output.write_text("\n".join(lines), encoding="utf-8")
    return output


